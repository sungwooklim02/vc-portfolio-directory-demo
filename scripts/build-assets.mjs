/**
 * build-assets.mjs — every generated static asset, rebuilt on each build (and before `next dev`).
 *
 *   1. Webfont chunks + @font-face CSS          scripts/fonts/build-fonts.mjs
 *   2. Vendor bundles (esbuild, IIFE globals)   public/vendor/three-lite-<v>.min.js, echarts-lite-<v>.min.js
 *   3. Local geodata                            public/vendor/geo/countries-110m-<v>.json (no tile server)
 *   4. Licence texts of everything shipped      public/vendor/licenses/*
 *   5. Favicon from lib/firm-mark.mjs           public/favicon.svg
 *   6. Team avatars (DiceBear Notionists, CC0)  public/img/team/*.svg (scripts/gen-avatars.mjs)
 *
 * Generated files are gitignored (see .gitignore) except the licence texts, which are committed and
 * re-copied here so a version bump updates them. Nothing is fetched from the network: the inputs are
 * the font source in scripts/fonts/src and the exact versions pinned in package.json.
 * Reproduce a single vendor bundle by hand (same flags as below), e.g.:
 *   npx esbuild scripts/vendor/three.entry.js --bundle --format=iife --global-name=THREE_LITE \
 *     --minify --legal-comments=none --target=es2020 --outfile=public/vendor/three-lite-0.186.1.min.js
 * (the build also prepends a one-line licence banner; see scripts/vendor/README.md)
 */
import { build } from "esbuild";
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(ROOT, "package.json"));
const VENDOR = join(ROOT, "public", "vendor");
const version = (pkg) => JSON.parse(readFileSync(join(ROOT, "node_modules", pkg, "package.json"), "utf8")).version;

const t0 = Date.now();

// 1. fonts
await import("./fonts/build-fonts.mjs");

// 2. vendor bundles
mkdirSync(VENDOR, { recursive: true });
for (const n of readdirSync(VENDOR)) if (/-lite-.*\.min\.js$/.test(n)) unlinkSync(join(VENDOR, n));
const bundles = [
  {
    entry: "scripts/vendor/three.entry.js",
    global: "THREE_LITE",
    out: `three-lite-${version("three")}.min.js`,
    banner: `three.js ${version("three")} (core + OrbitControls, RoomEnvironment, RoundedBoxGeometry) | MIT | licenses/three-LICENSE.txt`,
  },
  {
    entry: "scripts/vendor/echarts.entry.js",
    global: "ECHARTS_LITE",
    out: `echarts-lite-${version("echarts")}.min.js`,
    banner: `Apache ECharts ${version("echarts")} (Apache-2.0, see licenses/echarts-NOTICE.txt) + zrender ${version("zrender")} (BSD-3-Clause) + tslib (0BSD) + topojson-client ${version("topojson-client")} (ISC)`,
  },
];
for (const b of bundles) {
  await build({
    entryPoints: [join(ROOT, b.entry)],
    bundle: true,
    format: "iife",
    globalName: b.global,
    minify: true,
    legalComments: "none",
    banner: { js: `/*! ${b.banner} | index: vendor/LICENSES.md */` },
    target: "es2020",
    outfile: join(VENDOR, b.out),
    logLevel: "warning",
    define: { "process.env.NODE_ENV": '"production"' },
  });
  const buf = readFileSync(join(VENDOR, b.out));
  console.log(`  vendor ${b.out.padEnd(32)} ${String(buf.length).padStart(8)} B  gzip-9 ${gzipSync(buf, { level: 9 }).length} B`);
}

// 3. geodata (TopoJSON as shipped by world-atlas; the client converts it with topojson-client)
const GEO = join(VENDOR, "geo");
mkdirSync(GEO, { recursive: true });
for (const n of readdirSync(GEO)) if (n.endsWith(".json")) unlinkSync(join(GEO, n));
const geoOut = `countries-110m-${version("world-atlas")}.json`;
copyFileSync(require.resolve("world-atlas/countries-110m.json"), join(GEO, geoOut));
console.log(`  geo    ${geoOut}`);

// file names for the client loader (lib/loadScript.ts) — derived from the installed versions, never hand-typed
writeFileSync(
  join(ROOT, 'lib', 'vendor.generated.ts'),
  `// GENERATED by scripts/build-assets.mjs — do not edit.
export const VENDOR = ${JSON.stringify({ three: { file: bundles[0].out, global: bundles[0].global }, echarts: { file: bundles[1].out, global: bundles[1].global }, geo: 'geo/' + geoOut }, null, 2)} as const;
`,
  'utf8',
);

// 4. licence texts of shipped third-party code/data (index: public/vendor/LICENSES.md)
const LIC = join(VENDOR, "licenses");
mkdirSync(LIC, { recursive: true });
const licences = [
  ["three", "LICENSE", "three-LICENSE.txt"],
  ["echarts", "LICENSE", "echarts-LICENSE.txt"],
  ["echarts", "NOTICE", "echarts-NOTICE.txt"],
  ["zrender", "LICENSE", "zrender-LICENSE.txt"],
  ["tslib", "LICENSE.txt", "tslib-LICENSE.txt"],
  ["topojson-client", "LICENSE", "topojson-client-LICENSE.txt"],
  ["world-atlas", "LICENSE", "world-atlas-LICENSE.txt"],
  ["fuse.js", "LICENSE", "fuse.js-LICENSE.txt"],
  ["es-hangul", "LICENSE", "es-hangul-LICENSE.txt"],
  ["lucide-react", "LICENSE", "lucide-react-LICENSE.txt"],
];
for (const [pkg, file, out] of licences) {
  const src = join(ROOT, "node_modules", pkg, file);
  if (!existsSync(src)) throw new Error(`licence file missing: node_modules/${pkg}/${file}`);
  const text = readFileSync(src, "utf8").replace(/\r\n/g, "\n");
  writeFileSync(join(LIC, out), text.endsWith("\n") ? text : text + "\n", "utf8");
}
console.log(`  licences ${licences.length} files -> public/vendor/licenses/`);
// 5. favicon from the single firm-mark source (lib/firm-mark.mjs) so header and tab icon never drift
const { firmMarkSvg } = await import("../lib/firm-mark.mjs");
writeFileSync(join(ROOT, "public", "favicon.svg"), firmMarkSvg(), "utf8");
console.log("  favicon public/favicon.svg (from lib/firm-mark.mjs)");

// 6. illustrated team avatars (CC0 Notionists via DiceBear) -> public/img/team/*.svg
await import("./gen-avatars.mjs");

console.log(`build-assets done in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
